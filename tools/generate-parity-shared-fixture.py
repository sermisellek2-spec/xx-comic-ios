"""Generate the Debug-only Swift provider from the actual common fixture bytes."""
import base64
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
fixture = root / 'docs/ios-parity-2.0.40/fixtures'
raw = (fixture / 'current-pages.json').read_bytes()
data = json.loads(raw)
assert data['schema'] == 1 and data['baseline'] == '696e80a44ab36b19de6f630565df32978e55a19e'
assert 0 <= data['readChapterIndex'] < data['chapterCount']
image = (fixture / 'current-page.png').read_bytes()
assert image[:8] == b'\x89PNG\r\n\x1a\n'
assert int.from_bytes(image[16:20], 'big') == 384 and int.from_bytes(image[20:24], 'big') == 384
image64 = base64.b64encode(image).decode('ascii')
chunks = '\n'.join(image64[i:i + 120] for i in range(0, len(image64), 120))
source = '''#if DEBUG
import Foundation

// Generated by tools/generate-parity-shared-fixture.py from the shared
// manifest and a real, retained 384x384 test input. Never used by Release.
enum MatrixSharedFixture {
    struct Document: Decodable {
        struct Option: Decodable { let label: String; let value: String }
        let titles: [String]
        let subtitle: String
        let tags: [String]
        let author: String
        let status: String
        let description: String
        let latestChapter: String
        let chapterCount: Int
        let readChapterIndex: Int
        let pagesPerChapter: Int
        let filterKey: String
        let filterLabel: String
        let filterOptions: [Option]
    }
    static let metadataSHA256 = "METADATA_SHA"
    static let imageSHA256 = "IMAGE_SHA"
    static let document = try! JSONDecoder().decode(Document.self, from: Data(manifest.utf8))
    static let png = Data(base64Encoded: encodedImage, options: .ignoreUnknownCharacters)!
    private static let manifest = #"""
MANIFEST
"""#
    private static let encodedImage = """
IMAGE_DATA
"""
}
#endif
'''
source = source.replace('METADATA_SHA', hashlib.sha256(raw).hexdigest()).replace('IMAGE_SHA', hashlib.sha256(image).hexdigest())
source = source.replace('MANIFEST', raw.decode('utf-8').rstrip()).replace('IMAGE_DATA', chunks)
target = root / 'ios/XXComic/MatrixSharedFixture.swift'
target.write_text(source, encoding='utf-8')
identity = '''import Foundation

// Generated alongside the Debug app provider; records its actual input identity.
enum ParityFixtureIdentity {
    static let fixtureID = "FIXTURE_ID"
    static let metadataSHA256 = "METADATA_SHA"
    static let imageSHA256 = "IMAGE_SHA"
}
'''
identity = identity.replace('FIXTURE_ID', data['fixtureID']).replace('METADATA_SHA', hashlib.sha256(raw).hexdigest()).replace('IMAGE_SHA', hashlib.sha256(image).hexdigest())
(root / 'ios/XXComicUITests/ParityFixtureIdentity.swift').write_text(identity, encoding='utf-8')
print('Generated Debug fixture:', target.relative_to(root), 'metadata/image SHA-256 recorded')
